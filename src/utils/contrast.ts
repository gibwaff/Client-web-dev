/**
 * @file contrast.ts
 * @description Чистые функции для расчета относительной яркости и коэффициента контрастности
 * согласно международной спецификации W3C WCAG 2.1 (Web Content Accessibility Guidelines).
 * 
 * ПОЧЕМУ ЭТО ВАЖНО:
 * Человеческий глаз воспринимает цвета неравномерно: зеленый свет кажется глазу намного
 * ярче синего при одинаковой физической энергии. Поэтому простой расчет среднего значения
 * каналов неприменим — требуется учет спектральной чувствительности глаза и гаммы sRGB.
 */

import type { RGB, ContrastResult } from '../types';
import { hexToRgb, isValidHex } from './color';

/**
 * Линеаризация значения цветового канала sRGB (удаление гамма-компрессии).
 * 
 * ПОЧЕМУ ТАК:
 * Цвета на мониторах кодируются с нелинейной гамма-кривой (~2.2-2.4).
 * Чтобы честно сложить яркости фотонов, необходимо преобразовать сжатое значение
 * канала [0, 255] обратно в линейную шкалу энергии [0, 1].
 * Если канал <= 0.04045, зависимость линейная (деление на 12.92),
 * иначе применяется степенная функция ((c + 0.055) / 1.055)^2.4.
 */
function channelLuminance(channel: number): number {
  const c = channel / 255;
  return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}

/**
 * Рассчитывает относительную яркость (Relative Luminance) цвета по стандарту WCAG 2.1.
 * Возвращает число от 0.0 (абсолютно черный) до 1.0 (абсолютно белый).
 * 
 * ПОЧЕМУ ЭТИ КОЭФФИЦИЕНТЫ:
 * - 0.2126 для Красного (Red)
 * - 0.7152 для Зеленого (Green) — колбочки глаза наиболее чувствительны к зеленой области спектра
 * - 0.0722 для Синего (Blue)
 * Сумма коэффициентов: 0.2126 + 0.7152 + 0.0722 = 1.0.
 */
export function getLuminance(rgb: RGB): number {
  const r = channelLuminance(rgb.r);
  const g = channelLuminance(rgb.g);
  const b = channelLuminance(rgb.b);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/**
 * Рассчитывает коэффициент контрастности (Contrast Ratio) между двумя цветами.
 * Возвращает число от 1.00 (нет контраста, один и тот же цвет) до 21.00 (максимальный контраст черный/белый).
 * 
 * ФОРМУЛА WCAG 2.1:
 * Ratio = (L1 + 0.05) / (L2 + 0.05),
 * где L1 — относительная яркость более светлого цвета,
 * а L2 — относительная яркость более темного цвета.
 * 
 * ПОЧЕМУ +0.05:
 * Константа 0.05 учитывает рассеяние света в оптической системе человеческого глаза
 * и фоновое освещение помещения (Flare light). Без нее деление на 0 при абсолютно черном цвете
 * было бы невозможным.
 */
export function calculateContrastRatio(color1: RGB, color2: RGB): number {
  const lum1 = getLuminance(color1);
  const lum2 = getLuminance(color2);

  // Находим, какой из двух цветов ярче, а какой темнее
  const lighter = Math.max(lum1, lum2);
  const darker = Math.min(lum1, lum2);

  // Вычисляем отношение по формуле WCAG
  const ratio = (lighter + 0.05) / (darker + 0.05);

  // Округляем до двух знаков после запятой для удобного отображения в UI
  return Math.round(ratio * 100) / 100;
}

/**
 * Проверяет соответствие контрастности стандарту доступности WCAG 2.1.
 * Принимает цвета как в формате RGB-объекта, так и в строковом HEX-виде.
 * 
 * КРИТЕРИИ СТАНДАРТА:
 * - WCAG AA (Минимальный порог): коэффициент >= 4.5:1 для обычного текста (или >= 3.0:1 для шрифтов от 18pt)
 * - WCAG AAA (Повышенный порог): коэффициент >= 7.0:1 для обычного текста (или >= 4.5:1 для крупных шрифтов)
 */
export function checkWcagContrast(
  foreground: RGB | string,
  background: RGB | string
): ContrastResult {
  // Приведение текста (foreground) к RGB объекту
  const fgRgb: RGB = typeof foreground === 'string'
    ? (isValidHex(foreground) ? hexToRgb(foreground) : { r: 0, g: 0, b: 0 })
    : foreground;

  // Приведение фона (background) к RGB объекту
  const bgRgb: RGB = typeof background === 'string'
    ? (isValidHex(background) ? hexToRgb(background) : { r: 255, g: 255, b: 255 })
    : background;

  // Расчет коэффициента
  const ratio = calculateContrastRatio(fgRgb, bgRgb);

  return {
    ratio,
    wcagAA: ratio >= 4.5,       // Стандартный критерий AA (4.5:1)
    wcagAAA: ratio >= 7.0,      // Строгий критерий AAA (7.0:1)
    wcagAALarge: ratio >= 3.0,  // Допуск для крупного заголовка AA (3.0:1)
    wcagAAALarge: ratio >= 4.5, // Допуск для крупного заголовка AAA (4.5:1)
  };
}

/**
 * Возвращает читаемую русскоязычную оценку контрастности и рекомендацию для пользователя.
 */
export function getContrastRatingLabel(result: ContrastResult): {
  badge: 'Отлично' | 'Хорошо' | 'Плохо';
  text: string;
} {
  if (result.wcagAAA) {
    return {
      badge: 'Отлично',
      text: 'Идеальный контраст. Соответствует высшему стандарту WCAG AAA для любого размера шрифта.',
    };
  }
  if (result.wcagAA) {
    return {
      badge: 'Хорошо',
      text: 'Хороший контраст. Соответствует стандарту WCAG AA для обычного текста интерфейса.',
    };
  }
  if (result.wcagAALarge) {
    return {
      badge: 'Плохо',
      text: 'Допустимо только для крупного шрифта (от 18pt или 14pt bold). Не рекомендуется для обычного текста.',
    };
  }
  return {
    badge: 'Плохо',
    text: 'Недостаточный контраст. Текст будет трудно прочесть людям с ослабленным зрением или при ярком свете.',
  };
}
